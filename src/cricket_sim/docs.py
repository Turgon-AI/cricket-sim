"""`cricket docs`: generate docs/DATA_DICTIONARY.md and docs/LINEAGE.md from the contracts.

Never edit those two files by hand: change the contract and regenerate. A test fails if they are stale.
"""

from . import contracts
from .paths import ROOT

DOCS = ROOT / "docs"
LAYER_ORDER = ["staging", "silver", "gold", "models"]
LAYER_NOTE = {
    "staging": "Third-party CSVs renamed and typed, one table per file. All restricted; never exported.",
    "silver": "Conformed facts as recorded: Cricsheet parsed into tables, reference lists, the Hawk-Eye link, "
              "third-party per-ball layers and venue/weather/player context. Every match, no scope.",
    "gold": "Everything derived. int_ = building blocks over all matches; dim_/fact_/map_/report_ = in-scope "
            "products. Only gold dim_/fact_/map_/report_ tables can be exported.",
    "models": "Written by `cricket model`: walk-forward ODI win probability and ball-outcome predictions (every "
              "prediction from a model trained on earlier seasons only), pre-match Elo, and the evaluation reports. "
              "See docs/MODEL_CARD.md.",
}


def _cell(text) -> str:
    return " ".join(str(text if text is not None else "").split()).replace("|", "\\|")


def dictionary_md() -> str:
    all_contracts = contracts.load_all()
    lines = ["# Data dictionary", "",
             "Generated by `cricket docs` from `contracts/` (Open Data Contract Standard v3.1.0). Do not edit.", ""]
    for layer in LAYER_ORDER:
        tables = [c for c in all_contracts.values() if c.layer == layer]
        lines += [f"## {layer.capitalize()}", "", LAYER_NOTE[layer], ""]
        lines += ["| table | one row is | key |", "|---|---|---|"]
        lines += [f"| [`{c.table}`](#{c.table}) | {_cell(c.obj['dataGranularityDescription'])} | "
                  f"{', '.join(c.primary_key) or '—'} |" for c in tables]
        lines.append("")
        for c in tables:
            p = c.props
            lines += [f"### {c.table}", "", _cell(c.obj["description"]), "",
                      f"- **One row is:** {_cell(c.obj['dataGranularityDescription'])}",
                      f"- **Key:** {', '.join(f'`{k}`' for k in c.primary_key) or 'none'}",
                      f"- **Kind:** {p['kind']} · **Sources:** {', '.join(p['sources'])}"
                      + (f" · **Built from:** {', '.join(f'`{u}`' for u in p.get('upstream', []))}" if p.get("upstream") else "")
                      + (f" · **Timing class:** `{p['timingClass']}`" if p.get("timingClass") else ""), ""]
            limitations = (c.doc.get("description") or {}).get("limitations")
            if limitations:
                lines += [f"- **Limitations:** {_cell(limitations)}", ""]
            show_timing = any(c.column_props(col).get("timingClass") for col in c.columns) and not p.get("timingClass")
            header = "| column | type | description |" + (" timing |" if show_timing else "")
            lines += [header, "|---|---|---|" + ("---|" if show_timing else "")]
            for col in c.columns:
                cp = c.column_props(col)
                unit = f" ({cp['unit']})" if cp.get("unit") else ""
                flags = " **key**" if col.get("primaryKey") else (" required" if col.get("required") else "")
                row = f"| `{col['name']}`{flags} | {col['physicalType']} | {_cell(col['description'])}{unit} |"
                if show_timing:
                    row += f" {cp.get('timingClass', '')} |"
                lines.append(row)
            lines.append("")
    return "\n".join(lines) + "\n"


def lineage_md() -> str:
    all_contracts = contracts.load_all()
    sources = sorted({s for c in all_contracts.values() for s in c.sources if s != "derived"})
    lines = ["# Lineage", "", "Generated by `cricket docs` from the `sources` and `upstream` of every contract. "
             "Restricted sources (never exported) are drawn with dashed borders.", "", "```mermaid", "flowchart LR"]
    from .lineage import SOURCE_LICENCE  # noqa: PLC0415 (lineage imports contracts)

    lines.append('  subgraph bronze["bronze (immutable snapshots)"]')
    lines += [f"    src_{s}[({s})]" for s in sources]
    lines.append("  end")
    for layer in LAYER_ORDER:
        lines.append(f'  subgraph {layer}["{layer}"]')
        lines += [f"    {t}[{t}]" for t, c in all_contracts.items() if c.layer == layer]
        lines.append("  end")
    for t, c in all_contracts.items():
        ups = c.props.get("upstream") or []
        lines += [f"  {u} --> {t}" for u in ups]
        if not ups:
            lines += [f"  src_{s} --> {t}" for s in c.sources if s != "derived"]
    restricted = [f"src_{s}" for s in sources if SOURCE_LICENCE.get(s) is None]
    if restricted:
        lines.append("  classDef restricted stroke-dasharray: 5 5")
        lines.append(f"  class {','.join(restricted)} restricted")
    lines += ["```", ""]
    return "\n".join(lines)


def refresh_card_stamps() -> bool:
    """Rewrite the build stamp line of the dataset and model cards from the current build, if one is built."""
    import json  # noqa: PLC0415

    from . import export  # noqa: PLC0415
    from .paths import GOLD, MODELS  # noqa: PLC0415

    if not (GOLD / "run.json").exists() or not (MODELS / "run.json").exists():
        return False
    facts = export.card_facts(json.loads((GOLD / "run.json").read_text()), json.loads((MODELS / "run.json").read_text()))
    for card in export.CARDS:
        path = DOCS / card
        path.write_text(export.refresh_stamp(path.read_text(), facts[card]))
    return True


def write_docs() -> None:
    (DOCS / "DATA_DICTIONARY.md").write_text(dictionary_md())
    (DOCS / "LINEAGE.md").write_text(lineage_md())
    print("wrote docs/DATA_DICTIONARY.md and docs/LINEAGE.md")
    if refresh_card_stamps():
        print("refreshed the build stamp line in docs/DATASET_CARD.md and docs/MODEL_CARD.md "
              "(edit the card text to show the new numbers; export refuses a card whose text disagrees)")
